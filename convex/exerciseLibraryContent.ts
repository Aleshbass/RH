/** Clip id for an exercise slug and side ("L" is the left version). */
export function clipIdFor(slug: string, sided: boolean, side?: "L" | "R" | null) {
  if (!sided) return slug;
  return `${slug}-${side === "R" ? "right" : "left"}`;
}
