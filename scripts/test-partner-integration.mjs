import dotenv from 'dotenv';
dotenv.config({ path: '.env.local' });

import { ConvexHttpClient } from "convex/browser";
import { api } from "../convex/_generated/api.js";

const convexUrl = process.env.NEXT_PUBLIC_CONVEX_URL;
if (!convexUrl) {
  console.error("❌ NEXT_PUBLIC_CONVEX_URL is not set in .env.local");
  process.exit(1);
}

console.log("=================================================");
console.log("  REHABIFY PARTNER API & TRACKING LIVE TEST SUITE");
console.log("=================================================");
console.log(`📡 Connecting to Convex Backend: ${convexUrl}\n`);

const client = new ConvexHttpClient(convexUrl);

async function runTests() {
  let passed = 0;
  let failed = 0;

  // ──────────────────────────────────────────────────
  // TEST 1: API Key Validation (like Stripe / Cal.com test mode)
  // ──────────────────────────────────────────────────
  console.log("--- [Test 1] Partner API Key Authentication ---");
  try {
    const validSandbox = await client.query(api.partners.validatePartnerApiKey, {
      apiKey: "sk_test_rehabify_sandbox",
    });

    if (validSandbox && validSandbox.isSandbox && validSandbox.code === "sandbox_partner") {
      console.log("✅ Valid Test Key ('sk_test_rehabify_sandbox') accepted:");
      console.log(`   Partner Name: ${validSandbox.name}`);
      console.log(`   Tier: ${validSandbox.tier} | Sandbox Mode: ${validSandbox.isSandbox}`);
      passed++;
    } else {
      console.error("❌ Valid sandbox key was rejected or returned unexpected response", validSandbox);
      failed++;
    }

    const invalidKey = await client.query(api.partners.validatePartnerApiKey, {
      apiKey: "sk_invalid_fake_key_12345",
    });

    if (invalidKey === null) {
      console.log("✅ Invalid Key ('sk_invalid_fake_key_12345') successfully rejected (returned null)");
      passed++;
    } else {
      console.error("❌ Invalid key was accepted when it should be rejected", invalidKey);
      failed++;
    }
  } catch (err) {
    console.error("❌ Test 1 failed with error:", err.message);
    failed++;
  }

  // ──────────────────────────────────────────────────
  // TEST 2: Inbound Referral Creation with Partner Generated ID
  // ──────────────────────────────────────────────────
  console.log("\n--- [Test 2] Create Referral with Partner Generated ID ---");
  const testPartnerRef = "CAL-COM-" + Date.now().toString().slice(-6);
  let createdReferralId = null;
  let generatedTrackingCode = null;

  try {
    const referralPayload = {
      partnerCode: "sandbox_partner",
      partnerExternalId: testPartnerRef, // The ID generated by the partner (e.g. Cal.com / HMO)
      patientFirstName: "Babatunde",
      patientLastName: "Adeyemi",
      patientPhone: "+2348039988776",
      patientEmail: "babatunde.adeyemi@example.com",
      city: "Lagos",
      area: "Ikeja GRA",
      hospitalClinic: "Cal.com Health Partner Portal",
      condition: "Post-Op Anterior Cruciate Ligament (ACL) Tear",
      clinicalNotes: "Patient underwent ACL reconstruction 3 weeks ago. Needs rehabilitation protocol.",
      priority: "high",
      recommendedSessions: 8,
      billingMode: "corporate_sponsored",
      callbackUrl: "https://partner-webhook.example.com/rehabify",
    };

    console.log(`Submitting referral with partner's custom ID: ${testPartnerRef}...`);
    const result = await client.mutation(api.partners.createPartnerReferral, referralPayload);

    if (result && result.referralId && result.trackingCode) {
      createdReferralId = result.referralId;
      generatedTrackingCode = result.trackingCode;
      console.log("✅ Referral Created Successfully:");
      console.log(`   Referral ID (Convex): ${result.referralId}`);
      console.log(`   Generated Tracking Code: ${result.trackingCode}`);
      console.log(`   Partner Custom Ref: ${result.partnerExternalId}`);
      console.log(`   Status: ${result.status}`);
      passed++;
    } else {
      console.error("❌ Failed to create referral:", result);
      failed++;
    }
  } catch (err) {
    console.error("❌ Test 2 failed with error:", err.message);
    failed++;
  }

  // ──────────────────────────────────────────────────
  // TEST 3: Track Patient via Partner's Custom Generated ID
  // ──────────────────────────────────────────────────
  console.log("\n--- [Test 3] Track Patient using Partner Generated ID ---");
  try {
    console.log(`Querying /track by partnerExternalId: '${testPartnerRef}'...`);
    const trackedByPartnerId = await client.query(api.partners.getReferralDetails, {
      identifier: testPartnerRef,
      partnerCode: "sandbox_partner",
    });

    if (
      trackedByPartnerId &&
      trackedByPartnerId.partnerExternalId === testPartnerRef &&
      trackedByPartnerId.patient.firstName === "Babatunde"
    ) {
      console.log("✅ SUCCESS: Found referral using Partner's Generated ID!");
      console.log(`   Patient: ${trackedByPartnerId.patient.firstName} ${trackedByPartnerId.patient.lastName}`);
      console.log(`   Condition: ${trackedByPartnerId.clinicalNotes.condition}`);
      console.log(`   Tracking Code: ${trackedByPartnerId.trackingCode}`);
      console.log(`   Status: ${trackedByPartnerId.status}`);
      console.log(`   Sessions: ${trackedByPartnerId.sessions.completed} / ${trackedByPartnerId.sessions.total}`);
      passed++;
    } else {
      console.error("❌ Could not find referral by partner external ID", trackedByPartnerId);
      failed++;
    }
  } catch (err) {
    console.error("❌ Test 3 failed with error:", err.message);
    failed++;
  }

  // ──────────────────────────────────────────────────
  // TEST 4: Track Patient via Tracking Code (e.g. RHB-xxxxx)
  // ──────────────────────────────────────────────────
  console.log("\n--- [Test 4] Track Patient using Tracking Code ---");
  try {
    console.log(`Querying /track by trackingCode: '${generatedTrackingCode}'...`);
    const trackedByCode = await client.query(api.partners.getReferralDetails, {
      identifier: generatedTrackingCode,
      partnerCode: "sandbox_partner",
    });

    if (trackedByCode && trackedByCode.trackingCode === generatedTrackingCode) {
      console.log("✅ SUCCESS: Found referral using human Tracking Code!");
      passed++;
    } else {
      console.error("❌ Could not find referral by tracking code", trackedByCode);
      failed++;
    }
  } catch (err) {
    console.error("❌ Test 4 failed with error:", err.message);
    failed++;
  }

  // ──────────────────────────────────────────────────
  // TEST 5: List Partner Referrals
  // ──────────────────────────────────────────────────
  console.log("\n--- [Test 5] List Referrals for Partner ---");
  try {
    const list = await client.query(api.partners.listPartnerReferrals, {
      partnerCode: "sandbox_partner",
      limit: 5,
    });

    if (Array.isArray(list) && list.length > 0) {
      console.log(`✅ SUCCESS: Retrieved ${list.length} referrals for partner:`);
      list.slice(0, 3).forEach((item, idx) => {
        console.log(`   [${idx + 1}] Code: ${item.trackingCode} | Patient: ${item.patientName} | Status: ${item.status} | PartnerRef: ${item.partnerExternalId || "N/A"}`);
      });
      passed++;
    } else {
      console.error("❌ List referrals returned empty or non-array", list);
      failed++;
    }
  } catch (err) {
    console.error("❌ Test 5 failed with error:", err.message);
    failed++;
  }

  // ──────────────────────────────────────────────────
  // TEST 6: Provider Directory Search
  // ──────────────────────────────────────────────────
  console.log("\n--- [Test 6] Verified Provider Directory Search ---");
  try {
    const providers = await client.query(api.partners.searchVerifiedProviders, {
      city: "Lagos",
      limit: 5,
    });

    console.log(`✅ SUCCESS: Provider directory query returned ${providers.length} verified providers.`);
    if (providers.length > 0) {
      console.log(`   Sample Provider: ${providers[0].name} (${providers[0].licenseNumber}) - ${providers[0].city}`);
    }
    passed++;
  } catch (err) {
    console.error("❌ Test 6 failed with error:", err.message);
    failed++;
  }

  // ──────────────────────────────────────────────────
  // SUMMARY
  // ──────────────────────────────────────────────────
  console.log("\n=================================================");
  console.log(`  TEST RESULTS: ${passed} PASSED | ${failed} FAILED`);
  console.log("=================================================");

  if (failed === 0) {
    console.log("🎉 ALL BACKEND APIS & PARTNER TRACKING ARE 100% OPERATIONAL!");
    process.exit(0);
  } else {
    process.exit(1);
  }
}

runTests();
